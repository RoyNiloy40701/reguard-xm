def dictionary(panels: dict[str, pd.DataFrame]) -> str:
    lines = ["# Data dictionary (generated by scripts/build_dataset.py)", "",
             "All features use information up to and including date t. Targets use t+1 onward.",
             "Test-period rows (date >= test_start) are stored separately and locked.", ""]
    for name, df in panels.items():
        lines += [f"## {name}", "", "| Column | Type | Non-missing | Description |", "|---|---|---|---|"]
        for c in df.columns:
            lines.append(f"| `{c}` | {df[c].dtype} | {df[c].notna().mean():.1%} | {DESCR.get(c, '')} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tiers", default="B,DSE", help="comma list of B, DSE")
    args = ap.parse_args()
    tiers = {t.strip().upper() for t in args.tiers.split(",")}
    cfg = load_yaml("processing.yaml")
    PROCESSED_ROOT.mkdir(parents=True, exist_ok=True)
    summary, panels = {"config": cfg, "panels": []}, {}
    t0 = time.time()

    if "B" in tiers:
        print("[Tier B] ETF panel ...", flush=True)
        etf, etf_chk = tierb.build_etf_panel(cfg)
        etf_chk.to_csv(PROCESSED_ROOT / "tierb_etf_checks.csv", index=False)
        summary["panels"].append(save_panel(etf, "tierb_etf", cfg["test_start"], cfg["horizons"]))
        cal = pd.DatetimeIndex(sorted(etf["date"].unique()))
        w = make_windows(cal, cfg["walk_forward"]["tierb_first_window"], cfg["test_start"],
                         cfg["embargo_days"], cfg["walk_forward"]["min_train_days"])
        w.to_csv(PROCESSED_ROOT / "splits_tierb.csv", index=False)
        summary["tierb_windows"] = len(w)
        panels["tierb_etf"] = etf
        print("[Tier B] index panel ...", flush=True)
        idx, idx_chk = tierb.build_index_panel(cfg)
        idx_chk.to_csv(PROCESSED_ROOT / "tierb_index_checks.csv", index=False)
        summary["panels"].append(save_panel(idx, "tierb_index", cfg["test_start"], cfg["horizons"]))
        panels["tierb_index"] = idx
        print(f"  ETF rows={len(etf):,}  index rows={len(idx):,}  windows={len(w)}  ({time.time()-t0:.0f}s)", flush=True)

    if "DSE" in tiers:
        print("[DSE] equity panel ...", flush=True)
        out = dse.build_dse_panel(cfg)
        summary["panels"].append(save_panel(out["panel"], "dse_equity", cfg["test_start"], cfg["horizons"]))
        out["universe"].to_csv(PROCESSED_ROOT / "dse_universe.csv", index=False)
        out["lifetimes"].to_csv(PROCESSED_ROOT / "dse_lifetimes.csv", index=False)
        out["quality"].to_csv(PROCESSED_ROOT / "dse_quality.csv", index=False)
        mk = out["market"]
        mk[mk["date"] < pd.Timestamp(cfg["test_start"])].to_csv(PROCESSED_ROOT / "dse_market.csv", index=False)
        w = make_windows(out["calendar"], cfg["walk_forward"]["dse_first_window"], cfg["test_start"],
                         cfg["embargo_days"], cfg["walk_forward"]["min_train_days"])
        w.to_csv(PROCESSED_ROOT / "splits_dse.csv", index=False)
        summary["dse_windows"] = len(w)
        print("[DSE] survivorship audit (source B) ...", flush=True)
        aud = dse.survivorship_audit(cfg)
        aud.to_csv(PROCESSED_ROOT / "dse_survivorship_audit.csv", index=False)
        summary["dse_audit_classes"] = aud["classification"].str.replace(r"rename_of_.*", "rename", regex=True).value_counts().to_dict()
        panels["dse_equity"] = out["panel"]
        print(f"  DSE rows={len(out['panel']):,}  windows={len(w)}  ({time.time()-t0:.0f}s)", flush=True)

    summary["build_seconds"] = round(time.time() - t0, 1)
    (PROCESSED_ROOT / "build_summary.json").write_text(json.dumps(summary, indent=2, default=str), encoding="utf-8")
    DOCS_ROOT.mkdir(parents=True, exist_ok=True)
    (DOCS_ROOT / "data_dictionary.md").write_text(dictionary(panels), encoding="utf-8")
    for p in summary["panels"]:
        print(f"  {p['panel']}: dev={p['dev_rows']:,} test(locked)={p['test_rows']:,} purged targets={p['boundary_purged_targets']:,}")
    print("Done. Next: python scripts/validate_dataset.py")


if __name__ == "__main__":
    main()
